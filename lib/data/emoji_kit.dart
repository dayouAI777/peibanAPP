  static final List<String> all = List.unmodifiable([
    for (final group in groups) ...group.emojis,
  ]);

  static final Set<String> _catalog = all.toSet();

  // 历史按最近到最早排列。同频时优先显示最近选过的表情。
  static List<String> frequent(Iterable<String> history) {
    final counts = <String, int>{};
    final recency = <String, int>{};
    for (final emoji in history) {
      if (!_catalog.contains(emoji)) continue;
      recency.putIfAbsent(emoji, () => recency.length);
      counts.update(emoji, (count) => count + 1, ifAbsent: () => 1);
    }
    final ranked = counts.keys.toList()
      ..sort((a, b) {
        final byCount = counts[b]!.compareTo(counts[a]!);
        return byCount == 0 ? recency[a]!.compareTo(recency[b]!) : byCount;
      });
    return ranked.take(24).toList();
  }

